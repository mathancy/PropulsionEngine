//! The C++ generator (SPEC 11).
//!
//! PropulsionMKI is C++, and its design doc plans readable generated classes (`FG_Player.generated.h`
//! and `.cpp`, with `OnBeginPlay` and `OnTick`). This module turns a checked `.prop` file into
//! exactly that, standing on the small runtime in `cpp/PropulsionScriptRuntime.h`.
//!
//! The generated code means the same as the reference interpreter in `runtime/`; a differential
//! test compiles it and runs the same scenarios to check.

use crate::ast::*;
use crate::nodes::parse_marker;
use crate::project::{ActionSig, Project};
use crate::ty::Type;
use std::collections::{BTreeSet, HashMap};

/// The generated files for one `.prop` file.
#[derive(Debug, Clone)]
pub struct Generated {
    /// The file this came from, as the project knows it (`behaviors/door.prop`).
    pub key: String,
    pub class_name: String,
    pub header_name: String,
    pub header: String,
    pub source_name: String,
    pub source: String,
}

/// The C++ class name for a file key: `behaviors/game_state.prop` becomes `FG_GameState`.
pub fn class_name(key: &str) -> String {
    format!("FG_{}", script_name(key))
}

/// The script's name: `behaviors/game_state.prop` becomes `GameState`.
fn script_name(key: &str) -> String {
    let stem = key.rsplit('/').next().unwrap_or(key);
    let stem = stem.strip_suffix(".prop").unwrap_or(stem);
    let mut out = String::new();
    for part in stem.split(|c: char| !c.is_alphanumeric()).filter(|p| !p.is_empty()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}

/// Generate C++ for every file in the project.
pub fn generate_all(project: &Project) -> Result<Vec<Generated>, String> {
    let mut classes: HashMap<String, String> = HashMap::new();
    let mut seen: HashMap<String, String> = HashMap::new();
    for key in project.files.keys() {
        let class = class_name(key);
        if let Some(other) = seen.insert(class.clone(), key.clone()) {
            return Err(format!("`{other}` and `{key}` would both become the C++ class `{class}`; rename one of them"));
        }
        classes.insert(key.clone(), class);
    }
    let mut out = Vec::new();
    for (key, loaded) in &project.files {
        let file = loaded.parsed.as_ref().map_err(|e| format!("{key}: {e}"))?;
        out.push(Gen::new(project, &classes, key, file).run()?);
    }
    Ok(out)
}

/// The registry the engine uses to find a script by the path a scene or object refers to it by.
/// It is also the one translation unit that includes every generated source, so a build only has
/// to compile this file. Entries are sorted by path so the output doesn't depend on load order.
pub fn generate_registry(all: &[Generated]) -> String {
    let mut sorted: Vec<&Generated> = all.iter().collect();
    sorted.sort_by(|a, b| a.key.cmp(&b.key));

    let mut s = String::new();
    s.push_str("// Generated by propc. Do not edit.\n");
    s.push_str("// The script registry: maps a .prop path to the class that runs it.\n\n");
    s.push_str("#include \"PropulsionScriptRuntime.h\"\n\n");
    for g in &sorted {
        s.push_str(&format!("#include \"{}\"\n", g.source_name));
    }
    s.push_str("\nnamespace Propulsion::Script {\n\n");
    s.push_str("const std::vector<ScriptEntry>& ScriptRegistry() {\n");
    s.push_str("    static const std::vector<ScriptEntry> entries = {\n");
    for g in &sorted {
        s.push_str(&format!(
            "        {{ {}, {}::kScriptName, [](World& world, const glm::vec3& at, const std::vector<Arg>& overrides) {{ return world.Spawn<{}>(at, overrides); }} }},\n",
            c_str(&g.key),
            g.class_name,
            g.class_name
        ));
    }
    s.push_str("    };\n    return entries;\n}\n\n}  // namespace Propulsion::Script\n");
    s
}

