/// A name that is safe to use in C++.
fn ident(name: &str) -> String {
    if RESERVED.contains(&name) || name.starts_with('_') || name.starts_with("FG_") {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

fn cpp_type(t: &Type) -> String {
    match t {
        Type::Integer => "int".into(),
        Type::Decimal => "float".into(),
        Type::Boolean => "bool".into(),
        Type::Text => "std::string".into(),
        Type::Vector2 => "glm::vec2".into(),
        Type::Vector3 => "glm::vec3".into(),
        Type::Color => "glm::vec4".into(),
        Type::Entity => "Object*".into(),
        Type::Timer => "Timer".into(),
        Type::Gate => "bool".into(),
        Type::Enum(n) => ident(n),
        Type::Struct(n) if n == "hit" => "HitResult".into(),
        Type::Struct(n) => ident(n),
        Type::Duration => "double".into(),
        Type::List(inner) => format!("std::vector<{}>", cpp_type(inner)),
    }
}

fn float_lit(d: f64) -> String {
    format!("{d:?}f")
}

fn string_lit(s: &str) -> String {
    format!("std::string(\"{}\")", s.replace('\\', "\\\\").replace('"', "\\\""))
}

fn c_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

#[derive(Debug, Clone)]
struct VarInfo {
    ty: Type,
}

#[derive(Debug, Clone)]
struct EntityInfo {
    /// The script class the entity runs, if the header says (`file:"..."`).
    class: Option<String>,
}

struct Gen<'a> {
    project: &'a Project,
    classes: &'a HashMap<String, String>,
    key: &'a str,
    file: &'a File,
    class: String,

    vars: HashMap<String, VarInfo>,
    entities: HashMap<String, EntityInfo>,
    /// `needs file ... as Name`: alias -> class.
    aliases: HashMap<String, String>,
    systems: Vec<String>,
    startup: Vec<String>,
    uses: BTreeSet<String>,

    /// `only once as Greeting:` and friends: the name, and the line of the statement it starts over.
    latches: HashMap<String, usize>,
    /// The values of the enums: value -> the enum it belongs to.
    enum_values: HashMap<String, String>,

    /// Local names in scope, with the script class an entity local runs, if known.
    scopes: Vec<HashMap<String, Option<String>>>,
    /// The return type of the action being generated (`None` for handlers and void actions).
    returns: Option<Type>,
    /// Inside a delayed block (a lambda), `finish` is a plain `return;`.
    lambda_depth: usize,
    counter: usize,
    ind: usize,
    body: String,
}

impl<'a> Gen<'a> {
    fn new(project: &'a Project, classes: &'a HashMap<String, String>, key: &'a str, file: &'a File) -> Self {
        Gen {
            project,
            classes,
            key,
            file,
            class: classes[key].clone(),
            vars: HashMap::new(),
            entities: HashMap::new(),
            aliases: HashMap::new(),
            systems: Vec::new(),
            startup: Vec::new(),
            uses: BTreeSet::new(),
            latches: HashMap::new(),
            enum_values: HashMap::new(),
            scopes: Vec::new(),
            returns: None,
            lambda_depth: 0,
            counter: 0,
            ind: 0,
            body: String::new(),
        }
    }

    fn dep_class(&self, rel: &str) -> Option<String> {
        let loaded = &self.project.files[self.key];
        let dep_key = loaded.deps.get(rel)?.as_ref().ok()?;
        self.classes.get(dep_key).cloned()
    }

    fn run(mut self) -> Result<Generated, String> {
        // What the header declares.
        for d in &self.file.header {
            match &d.kind {
                DeclKind::Variable { name, ty, .. } => {
                    self.vars.insert(name.clone(), VarInfo { ty: Type::from_expr(ty) });
                }
                DeclKind::Constant { name, ty, .. } => {
                    self.vars.insert(name.clone(), VarInfo { ty: Type::from_expr(ty) });
                }
                DeclKind::NeedsSystem(n) => self.systems.push(n.clone()),
                DeclKind::Enum { name, values } => {
                    for v in values {
                        self.enum_values.insert(v.clone(), name.clone());
                    }
                }
                DeclKind::NeedsFile { file, alias, when } => {
                    if let (Some(a), Some(class)) = (alias, self.dep_class(file)) {
                        self.aliases.insert(a.clone(), class.clone());
                        self.uses.insert(class.clone());
                        if when.as_deref() == Some("startup") {
                            self.startup.push(class);
                        }
                    }
                }
                DeclKind::NeedsEntity { name, file, .. } => {
                    let class = self.dep_class(file);
                    if let Some(c) = &class {
                        self.uses.insert(c.clone());
                    }
                    self.entities.insert(name.clone(), EntityInfo { class });
                }
                DeclKind::NeedsEntities { name, file, .. } => {
                    let class = file.as_ref().and_then(|f| self.dep_class(f));
                    if let Some(c) = &class {
                        self.uses.insert(c.clone());
                    }
                    self.entities.insert(name.clone(), EntityInfo { class });
                }
                _ => {}
            }
        }

        for item in &self.file.implement {
            let (ItemKind::Handler { body, .. } | ItemKind::Action { body, .. }) = &item.kind;
            latch_sites(body, &mut self.latches, &mut Vec::new());
        }

        let header = self.header();
        let source = self.source()?;
        let class = self.class.clone();
        Ok(Generated {
            key: self.key.to_string(),
            header_name: format!("{class}.generated.h"),
            source_name: format!("{class}.generated.cpp"),
            class_name: class,
            header,
            source,
        })
    }

    // ───────────────────────────── the header ─────────────────────────────

    fn banner(&self, file_name: &str) -> String {
        let bar = "// ═══════════════════════════════════════════════════════════════\n";
        format!(
            "{bar}// {file_name}\n// Generated from: {}\n// Do not edit this file: change the .prop file and generate again.\n{bar}\n",
            self.key
        )
    }

    fn header(&self) -> String {
        let class = &self.class;
        let mut s = self.banner(&format!("{class}.generated.h"));
        s.push_str("#pragma once\n\n#include \"PropulsionScriptRuntime.h\"\n\nnamespace Propulsion::Script {\n\n");
        s.push_str(&format!("class {class} : public ScriptBehavior {{\npublic:\n"));
        s.push_str(&format!("    static constexpr const char* kScriptName = {};\n", c_str(&script_name(self.key))));
        s.push_str("    const char* ScriptName() const override { return kScriptName; }\n");

        let tags: Vec<String> = self
            .file
            .header
            .iter()
            .filter_map(|d| if let DeclKind::Tag(t) = &d.kind { Some(c_str(t)) } else { None })
            .collect();
        if !tags.is_empty() {
            s.push_str(&format!("    std::vector<std::string> Tags() const override {{ return {{ {} }}; }}\n", tags.join(", ")));
        }
        s.push_str(&format!("    std::unique_ptr<ScriptBehavior> Clone() const override {{ return std::make_unique<{class}>(*this); }}\n"));

        // Enums and structs are types of this class, so two scripts can each have their own `Mode` or `Item`.
        for d in &self.file.header {
            match &d.kind {
                DeclKind::Enum { name, values } => {
                    let n = ident(name);
                    s.push_str(&format!("\n    // ─── enum {name} ───\n"));
                    s.push_str(&format!("    enum class {n} {{ {} }};\n", values.iter().map(|v| ident(v)).collect::<Vec<_>>().join(", ")));
                }
                DeclKind::Struct { name, fields } => {
                    let n = ident(name);
                    s.push_str(&format!("\n    // ─── struct {name} ───\n    struct {n} {{\n"));
                    for (f, t) in fields {
                        s.push_str(&format!("        {} {}{{}};\n", cpp_type(&Type::from_expr(t)), ident(f)));
                    }
                    let same: Vec<String> = fields.iter().map(|(f, _)| format!("{0} == other.{0}", ident(f))).collect();
                    s.push_str(&format!("        bool operator==(const {n}& other) const {{ return {}; }}\n", same.join(" && ")));
                    s.push_str(&format!("        bool operator!=(const {n}& other) const {{ return !(*this == other); }}\n    }};\n"));
                }
                _ => {}
            }
        }

        // Variables and constants.
        s.push_str("\n    // ─── header: ───\n");
        let mut exposed = Vec::new();
        for d in &self.file.header {
            for line in self.notes_lines(&d.notes, 1) {
                s.push_str(&line);
            }
            match &d.kind {
                DeclKind::Variable { name, ty, value, parts, entries, exposed: is_exposed } => {
                    let t = Type::from_expr(ty);
                    let init = self.initializer(&t, value.as_ref(), parts, entries);
                    let comment = if *is_exposed { "  // exposed" } else { "" };
                    s.push_str(&format!("    {} {} = {};{comment}\n", cpp_type(&t), ident(name), init));
                    if *is_exposed {
                        exposed.push(name.clone());
                    }
                }
                DeclKind::Constant { name, ty, value, parts } => {
                    let t = Type::from_expr(ty);
                    let init = self.initializer(&t, value.as_ref(), parts, &[]);
                    let storage = if matches!(t, Type::Integer | Type::Decimal | Type::Boolean) {
                        "static constexpr"
                    } else {
                        "inline static const"
                    };
                    s.push_str(&format!("    {storage} {} {} = {};\n", cpp_type(&t), ident(name), init));
                }
                DeclKind::NeedsEntity { name, tag, .. } => {
                    s.push_str(&format!("    Object* {}() const {{ return world->FindByTag({}); }}  // needs entity, tag {}\n", ident(name), c_str(tag), c_str(tag)));
                }
                DeclKind::NeedsEntities { name, tag, .. } => {
                    s.push_str(&format!(
                        "    std::vector<Object*> {}() const {{ return world->AllByTag({}); }}  // needs entities, tag {}\n",
                        ident(name),
                        c_str(tag),
                        c_str(tag)
                    ));
                }
                DeclKind::NeedsComponent(n) => s.push_str(&format!("    // needs component {n}: the Object's {n}Component\n")),
                DeclKind::NeedsSystem(n) => s.push_str(&format!("    // needs system {n}: through world->host()\n")),
                DeclKind::NeedsFile { file, alias, .. } => {
                    s.push_str(&format!("    // needs file {}{}\n", c_str(file), alias.as_ref().map(|a| format!(" as {a}")).unwrap_or_default()));
                }
                DeclKind::Table { name, ty, rows } => {
                    let struct_name = ident(ty);
                    let struct_type = if ty == "hit" { "HitResult".to_string() } else { struct_name };
                    s.push_str(&format!("    // table {name}: its rows, found by key\n"));
                    s.push_str(&format!("    {struct_type} Row_{}(const std::string& key) const {{\n", ident(name)));
                    s.push_str(&format!("        static const std::vector<std::pair<std::string, {struct_type}>> rows = [] {{\n"));
                    s.push_str(&format!("            std::vector<std::pair<std::string, {struct_type}>> r;\n"));
                    for row in rows {
                        let sets: Vec<String> = row.values.iter().map(|(f, t)| format!("v.{} = {};", ident(f), self.term(t))).collect();
                        s.push_str(&format!("            {{ {struct_type} v{{}}; {} r.push_back({{{}, v}}); }}\n", sets.join(" "), c_str(&row.key)));
                    }
                    s.push_str("            return r;\n        }();\n");
                    s.push_str("        for (const auto& row : rows) {\n            if (row.first == key) return row.second;\n        }\n");
                    s.push_str(&format!("        world->Warn(\"`{name}` has no row \\\"\" + key + \"\\\"; used the defaults\");\n        return {struct_type}{{}};\n    }}\n"));
                }
                DeclKind::Enum { .. } | DeclKind::Struct { .. } => {}
                DeclKind::Tag(_) | DeclKind::Event(_) => {}
            }
        }

        // The state of `only once`, `first N times` and `alternate`, one counter per statement.
        let mut sites: Vec<(usize, String)> = Vec::new();
        for item in &self.file.implement {
            let (ItemKind::Handler { body, .. } | ItemKind::Action { body, .. }) = &item.kind;
            latch_sites(body, &mut HashMap::new(), &mut sites);
        }
        if !sites.is_empty() {
            s.push_str("\n    // ─── state of `only once`, `first N times` and `alternate` ───\n");
            for (line, what) in &sites {
                s.push_str(&format!("    int Latch_{line}_ = 0;  // {what}\n"));
            }
        }

        // Last-seen values for `when <Variable> changes:`.
        for item in &self.file.implement {
            if let ItemKind::Handler { trigger: Trigger::Changes(var), .. } = &item.kind {
                if let Some(info) = self.vars.get(var) {
                    s.push_str(&format!("    {} Last_{} = {{}};  // for `when {var} changes:`\n", cpp_type(&info.ty), ident(var)));
                }
            }
        }

        // Actions (public so other scripts can call them).
        let actions: Vec<&Item> = self.file.implement.iter().filter(|i| matches!(i.kind, ItemKind::Action { .. })).collect();
        if !actions.is_empty() {
            s.push_str("\n    // ─── actions ───\n");
            for item in actions {
                if let ItemKind::Action { name, params, gives, .. } = &item.kind {
                    s.push_str(&format!("    {} {}({});\n", self.ret_type(gives.as_ref()), ident(name), self.param_list(params)));
                }
            }
        }

        // Entry points.
        s.push_str("\n    // ─── entry points the World calls ───\n");
        if !exposed.is_empty() {
            s.push_str("    bool SetExposed(const std::string& name, const Value& value) override;\n");
        }
        let has = |f: &dyn Fn(&Trigger) -> bool| {
            self.file.implement.iter().any(|i| matches!(&i.kind, ItemKind::Handler { trigger, .. } if f(trigger)))
        };
        let needs_begin = has(&|t| matches!(t, Trigger::Created))
            || has(&|t| matches!(t, Trigger::Changes(_)))
            || !self.startup.is_empty()
            || self.file.header.iter().any(|d| matches!(&d.kind, DeclKind::Variable { ty: TypeExpr::Timer, .. }));
        if needs_begin {
            s.push_str("    void OnBeginPlay() override;\n");
        }
        if has(&|t| matches!(t, Trigger::Destroyed)) {
            s.push_str("    void OnDestroy() override;\n");
        }
        if has(&|t| matches!(t, Trigger::EveryFrame | Trigger::EverySeconds(_) | Trigger::Input { .. })) {
            s.push_str("    void OnTick(float DeltaTime) override;\n");
        }
        if has(&|t| matches!(t, Trigger::Touches { .. })) {
            s.push_str("    void OnOverlapBegin(Object* other) override;\n");
        }
        if has(&|t| matches!(t, Trigger::StopsTouching { .. })) {
            s.push_str("    void OnOverlapEnd(Object* other) override;\n");
        }
        if has(&|t| matches!(t, Trigger::Hits { .. })) {
            s.push_str("    void OnHit(Object* other) override;\n");
        }
        if has(&|t| matches!(t, Trigger::Damaged { .. })) {
            s.push_str("    void OnDamaged(float amount, Object* source) override;\n");
        }
        if self.file.implement.iter().any(|i| matches!(i.kind, ItemKind::Action { .. })) {
            s.push_str("    bool Message(const std::string& action, const std::vector<Arg>& args) override;\n");
        }
        if has(&|t| matches!(t, Trigger::Event(_))) {
            s.push_str("    void OnOwnEvent(const std::string& name) override;\n");
        }
        if has(&|t| matches!(t, Trigger::Sends { .. })) {
            s.push_str("    void OnEventFrom(ScriptBehavior* sender, const std::string& name) override;\n");
        }
        if has(&|t| matches!(t, Trigger::Changes(_))) {
            s.push_str("    bool FlushChanges() override;\n");
        }

        // Handler bodies.
        let handlers: Vec<(usize, &Item)> = self.file.implement.iter().enumerate().filter(|(_, i)| matches!(i.kind, ItemKind::Handler { .. })).collect();
        if !handlers.is_empty() {
            s.push_str("\nprivate:\n    // ─── handlers (implement:) ───\n");
            for (idx, item) in handlers {
                if let ItemKind::Handler { trigger, .. } = &item.kind {
                    s.push_str(&format!("    void {}({});\n", self.handler_name(idx, trigger), self.handler_params(trigger)));
                }
            }
        }
        s.push_str("};\n");

        // The text of an enum's values, for `print`, `text of` and `joined with`. It sits beside the class (not in
        // it), where the call finds it through the enum's type.
        for d in &self.file.header {
            if let DeclKind::Enum { name, values } = &d.kind {
                let n = ident(name);
                s.push_str(&format!("\ninline std::string ToText({class}::{n} v) {{\n    switch (v) {{\n"));
                for v in values {
                    s.push_str(&format!("        case {class}::{n}::{}: return {};\n", ident(v), c_str(v)));
                }
                s.push_str("    }\n    return {};\n}\n");
            }
        }
        s.push_str("\n}  // namespace Propulsion::Script\n");
        s
    }

    fn initializer(&self, ty: &Type, value: Option<&Term>, parts: &Parts, entries: &[Parts]) -> String {
        let part = |ps: &Parts, k: &str| {
            ps.iter()
                .find(|(n, _)| n == k)
                .map(|(_, t)| match t {
                    Term::Int(i) => float_lit(*i as f64),
                    Term::Decimal(d) => float_lit(*d),
                    _ => "0.0f".to_string(),
                })
                .unwrap_or_else(|| "0.0f".to_string())
        };
        let vector = |t: &Type, ps: &Parts| match t {
            Type::Vector2 => format!("glm::vec2({}, {})", part(ps, "x"), part(ps, "y")),
            Type::Vector3 => format!("glm::vec3({}, {}, {})", part(ps, "x"), part(ps, "y"), part(ps, "z")),
            Type::Color => format!("glm::vec4({}, {}, {}, {})", part(ps, "r"), part(ps, "g"), part(ps, "b"), part(ps, "a")),
            _ => "{}".to_string(),
        };
        match ty {
            Type::Vector2 | Type::Vector3 | Type::Color => vector(ty, parts),
            Type::List(el) => {
                if entries.is_empty() {
                    "{}".to_string()
                } else {
                    format!("{{ {} }}", entries.iter().map(|e| vector(el, e)).collect::<Vec<_>>().join(", "))
                }
            }
            Type::Timer => "{}".to_string(),
            Type::Gate => (!matches!(value, Some(Term::Name(n)) if n == "closed")).to_string(),
            Type::Enum(en) => match value {
                Some(Term::Name(n)) => format!("{}::{}", ident(en), ident(n)),
                _ => "{}".to_string(),
            },
            Type::Struct(_) => "{}".to_string(),
            Type::Entity => "nullptr".to_string(),
            Type::Integer => match value {
                Some(Term::Int(i)) => i.to_string(),
                _ => "0".to_string(),
            },
            Type::Decimal => match value {
                Some(Term::Int(i)) => float_lit(*i as f64),
                Some(Term::Decimal(d)) => float_lit(*d),
                _ => "0.0f".to_string(),
            },
            Type::Boolean => match value {
                Some(Term::Bool(b)) => b.to_string(),
                _ => "false".to_string(),
            },
            Type::Text => match value {
                Some(Term::Text(t)) => string_lit(t),
                _ => "std::string()".to_string(),
            },
            Type::Duration => "0.0".to_string(),
        }
    }

    fn ret_type(&self, gives: Option<&TypeExpr>) -> String {
        gives.map(|g| cpp_type(&Type::from_expr(g))).unwrap_or_else(|| "void".to_string())
    }

    fn param_list(&self, params: &[Param]) -> String {
        params.iter().map(|p| format!("{} {}", cpp_type(&Type::from_expr(&p.ty)), ident(&p.name))).collect::<Vec<_>>().join(", ")
    }

    fn handler_name(&self, idx: usize, t: &Trigger) -> String {
        let n = idx + 1;
        match t {
            Trigger::Created => format!("Handler{n}_OnBeginPlay"),
            Trigger::Destroyed => format!("Handler{n}_OnDestroy"),
            Trigger::EveryFrame => format!("Handler{n}_EveryFrame"),
            Trigger::EverySeconds(s) => format!("Handler{n}_Every{}Seconds", format!("{s}").replace('.', "_")),
            Trigger::Touches { file, .. } => format!("Handler{n}_OnOverlapBegin_{}", ident(file)),
            Trigger::StopsTouching { file, .. } => format!("Handler{n}_OnOverlapEnd_{}", ident(file)),
            Trigger::Changes(v) => format!("Handler{n}_OnChanged_{}", ident(v)),
            Trigger::Input { input, kind, .. } => {
                let k = if *kind == PressKind::Started { "Pressed" } else { "Released" };
                format!("Handler{n}_On{k}_{}", ident(input))
            }
            Trigger::Sends { file, event, .. } => format!("Handler{n}_On{}_From_{}", ident(event), ident(file)),
            Trigger::Event(e) => format!("Handler{n}_OnEvent_{}", ident(e)),
            Trigger::Damaged { .. } => format!("Handler{n}_OnDamaged"),
            Trigger::Hits { file, .. } => format!("Handler{n}_OnHit_{}", ident(file)),
        }
    }

    fn handler_params(&self, t: &Trigger) -> String {
        match t {
            Trigger::Touches { name, .. } | Trigger::StopsTouching { name, .. } | Trigger::Sends { name, .. } | Trigger::Hits { name, .. } => {
                format!("Object* {}", ident(name))
            }
            Trigger::Damaged { amount, source } => match source {
                Some(s) => format!("float {}, Object* {}", ident(amount), ident(s)),
                None => format!("float {}", ident(amount)),
            },
            _ => String::new(),
        }
    }

    // ───────────────────────────── comments ─────────────────────────────

    /// Comments above a line of code. A node marker becomes the engine doc's `// ─── Node: ... ───`.
    fn notes_lines(&self, notes: &Notes, depth: usize) -> Vec<String> {
        let pad = "    ".repeat(depth);
        notes
            .leading
            .iter()
            .map(|c| match parse_marker(c) {
                Some(m) => format!("{pad}// ─── Node: \"{}\" (ID: {}) ───\n", m.name, m.id),
                None if c.is_empty() => format!("{pad}//\n"),
                None => format!("{pad}// {c}\n"),
            })
            .collect()
    }

    // ───────────────────────────── the source ─────────────────────────────

    fn source(&mut self) -> Result<String, String> {
        let class = self.class.clone();
        let mut s = self.banner(&format!("{class}.generated.cpp"));
        s.push_str(&format!("#include \"{class}.generated.h\"\n"));
        for dep in self.uses.iter().filter(|c| **c != class) {
            s.push_str(&format!("#include \"{dep}.generated.h\"\n"));
        }
        s.push_str("\nnamespace Propulsion::Script {\n");

        // SetExposed
        let exposed: Vec<String> = self
            .file
            .header
            .iter()
            .filter_map(|d| match &d.kind {
                DeclKind::Variable { name, exposed: true, .. } => Some(name.clone()),
                _ => None,
            })
            .collect();
        if !exposed.is_empty() {
            s.push_str(&format!("\nbool {class}::SetExposed(const std::string& name, const Value& value) {{\n"));
            for n in &exposed {
                s.push_str(&format!("    if (name == {}) return AssignValue({}, value);\n", c_str(n), ident(n)));
            }
            s.push_str("    return false;\n}\n");
        }

        // Entry points, in the order the interpreter runs things.
        let items: Vec<(usize, &Item)> = self.file.implement.iter().enumerate().collect();
        let handlers: Vec<(usize, &Item, &Trigger)> = items
            .iter()
            .filter_map(|(i, it)| match &it.kind {
                ItemKind::Handler { trigger, .. } => Some((*i, *it, trigger)),
                _ => None,
            })
            .collect();

        // OnBeginPlay
        let timers: Vec<String> = self
            .file
            .header
            .iter()
            .filter_map(|d| match &d.kind {
                DeclKind::Variable { name, ty: TypeExpr::Timer, .. } => Some(name.clone()),
                _ => None,
            })
            .collect();
        let created: Vec<_> = handlers.iter().filter(|(_, _, t)| matches!(t, Trigger::Created)).collect();
        let watched: Vec<&String> = handlers
            .iter()
            .filter_map(|(_, _, t)| if let Trigger::Changes(v) = t { Some(v) } else { None })
            .collect();
        if !created.is_empty() || !watched.is_empty() || !self.startup.is_empty() || !timers.is_empty() {
            s.push_str(&format!("\nvoid {class}::OnBeginPlay() {{\n"));
            for t in &timers {
                s.push_str(&format!("    {}.Reset(*world);  // timers start when the script starts\n", ident(t)));
            }
            for dep in &self.startup {
                s.push_str(&format!("    world->Instance<{dep}>();  // needs file ... when:startup\n"));
            }
            for v in &watched {
                s.push_str(&format!("    Last_{0} = {0};\n", ident(v)));
            }
            for (idx, _, t) in &created {
                s.push_str(&format!("    {}();\n", self.handler_name(*idx, t)));
            }
            s.push_str("}\n");
        }

        // OnDestroy
        let destroyed: Vec<_> = handlers.iter().filter(|(_, _, t)| matches!(t, Trigger::Destroyed)).collect();
        if !destroyed.is_empty() {
            s.push_str(&format!("\nvoid {class}::OnDestroy() {{\n"));
            for (idx, _, t) in &destroyed {
                s.push_str(&format!("    {}();\n", self.handler_name(*idx, t)));
            }
            s.push_str("}\n");
        }

        // OnTick: frame handlers, input handlers, and interval handlers, in file order.
        let ticking: Vec<_> = handlers
            .iter()
            .filter(|(_, _, t)| matches!(t, Trigger::EveryFrame | Trigger::EverySeconds(_) | Trigger::Input { .. }))
            .collect();
        if !ticking.is_empty() {
            s.push_str(&format!("\nvoid {class}::OnTick(float DeltaTime) {{\n    (void)DeltaTime;\n"));
            for (idx, _, t) in &ticking {
                let call = format!("{}();", self.handler_name(*idx, t));
                s.push_str("    if (!IsAlive()) return;\n");
                match t {
                    Trigger::EveryFrame => s.push_str(&format!("    {call}\n")),
                    Trigger::EverySeconds(secs) => {
                        s.push_str(&format!("    if (IntervalDue({}, {})) {call}\n", idx, format!("{secs:?}")));
                    }
                    Trigger::Input { system, input, kind } => {
                        let method = if *kind == PressKind::Started { "Started" } else { "Stopped" };
                        s.push_str(&format!("    if (world->host().{method}(self, {}, {})) {call}\n", c_str(system), c_str(input)));
                    }
                    _ => {}
                }
            }
            s.push_str("}\n");
        }

        // Overlaps.
        for (stopping, entry, label) in [(false, "OnOverlapBegin", "begin"), (true, "OnOverlapEnd", "end")] {
            let these: Vec<_> = handlers
                .iter()
                .filter(|(_, _, t)| matches!((t, stopping), (Trigger::Touches { .. }, false) | (Trigger::StopsTouching { .. }, true)))
                .collect();
            if these.is_empty() {
                continue;
            }
            s.push_str(&format!("\nvoid {class}::{entry}(Object* other) {{  // overlap {label}\n"));
            for (idx, _, t) in these {
                let file = match t {
                    Trigger::Touches { file, .. } | Trigger::StopsTouching { file, .. } => file,
                    _ => unreachable!(),
                };
                let target = self.aliases.get(file).cloned().ok_or_else(|| format!("`{file}` isn't a file from the header"))?;
                s.push_str(&format!("    if (world->As<{target}>(other)) {}(other);\n", self.handler_name(*idx, t)));
            }
            s.push_str("}\n");
        }

        let hits: Vec<_> = handlers.iter().filter(|(_, _, t)| matches!(t, Trigger::Hits { .. })).collect();
        if !hits.is_empty() {
            s.push_str(&format!("\nvoid {class}::OnHit(Object* other) {{  // blocking collision\n"));
            for (idx, _, t) in hits {
                let Trigger::Hits { file, .. } = t else { unreachable!() };
                let target = self.aliases.get(file).cloned().ok_or_else(|| format!("`{file}` isn't a file from the header"))?;
                s.push_str(&format!("    if (world->As<{target}>(other)) {}(other);\n", self.handler_name(*idx, t)));
            }
            s.push_str("}\n");
        }
        let damaged: Vec<_> = handlers.iter().filter(|(_, _, t)| matches!(t, Trigger::Damaged { .. })).collect();
        if !damaged.is_empty() {
            s.push_str(&format!("\nvoid {class}::OnDamaged(float amount, Object* source) {{\n    (void)source;\n"));
            for (idx, _, t) in damaged {
                let Trigger::Damaged { source, .. } = t else { unreachable!() };
                let args = if source.is_some() { "amount, source" } else { "amount" };
                s.push_str(&format!("    {}({args});\n", self.handler_name(*idx, t)));
            }
            s.push_str("}\n");
        }

        // Messages: `tell Foe to TakeDamage amount:5` finds the action by name.
        let actions: Vec<(&String, &Vec<Param>)> = self
            .file
            .implement
            .iter()
            .filter_map(|i| if let ItemKind::Action { name, params, .. } = &i.kind { Some((name, params)) } else { None })
            .collect();
        if !actions.is_empty() {
            s.push_str(&format!("\nbool {class}::Message(const std::string& action, const std::vector<Arg>& args) {{\n    (void)args;\n"));
            for (name, params) in actions {
                let call: Vec<String> =
                    params.iter().map(|p| format!("Take<{}>(args, {})", cpp_type(&Type::from_expr(&p.ty)), c_str(&p.name))).collect();
                s.push_str(&format!("    if (action == {}) {{ {}({}); return true; }}\n", c_str(name), ident(name), call.join(", ")));
            }
            s.push_str("    return false;\n}\n");
        }

        // Events.
        let own: Vec<_> = handlers.iter().filter(|(_, _, t)| matches!(t, Trigger::Event(_))).collect();
        if !own.is_empty() {
            s.push_str(&format!("\nvoid {class}::OnOwnEvent(const std::string& name) {{\n"));
            for (idx, _, t) in own {
                if let Trigger::Event(e) = t {
                    s.push_str(&format!("    if (name == {}) {}();\n", c_str(e), self.handler_name(*idx, t)));
                }
            }
            s.push_str("}\n");
        }
        let from: Vec<_> = handlers.iter().filter(|(_, _, t)| matches!(t, Trigger::Sends { .. })).collect();
        if !from.is_empty() {
            s.push_str(&format!("\nvoid {class}::OnEventFrom(ScriptBehavior* sender, const std::string& name) {{\n"));
            for (idx, _, t) in from {
                if let Trigger::Sends { file, event, .. } = t {
                    let target = self.aliases.get(file).cloned().ok_or_else(|| format!("`{file}` isn't a file from the header"))?;
                    s.push_str(&format!(
                        "    if (sender && name == {} && dynamic_cast<{target}*>(sender)) {}(sender->self);\n",
                        c_str(event),
                        self.handler_name(*idx, t)
                    ));
                }
            }
            s.push_str("}\n");
        }

        // Variable changes.
        let changes: Vec<_> = handlers.iter().filter(|(_, _, t)| matches!(t, Trigger::Changes(_))).collect();
        if !changes.is_empty() {
            s.push_str(&format!("\nbool {class}::FlushChanges() {{\n    bool any = false;\n"));
            for (idx, _, t) in changes {
                if let Trigger::Changes(v) = t {
                    let v = ident(v);
                    s.push_str(&format!(
                        "    if ({v} != Last_{v}) {{\n        Last_{v} = {v};\n        any = true;\n        {}();\n    }}\n",
                        self.handler_name(*idx, t)
                    ));
                }
            }
            s.push_str("    return any;\n}\n");
        }

        // Handler and action bodies.
        for (idx, item) in items {
            s.push('\n');
            match &item.kind {
                ItemKind::Handler { trigger, body } => {
                    for line in self.notes_lines(&item.notes, 0) {
                        s.push_str(&line);
                    }
                    let trailing = item.notes.trailing.as_ref().map(|t| format!("  // {t}")).unwrap_or_default();
                    s.push_str(&format!(
                        "void {class}::{}({}) {{{trailing}\n",
                        self.handler_name(idx, trigger),
                        self.handler_params(trigger)
                    ));
                    self.scopes = vec![HashMap::new()];
                    match trigger {
                        Trigger::Touches { file, name }
                        | Trigger::StopsTouching { file, name }
                        | Trigger::Sends { file, name, .. }
                        | Trigger::Hits { file, name } => {
                            let class = self.aliases.get(file).cloned();
                            self.scopes[0].insert(name.clone(), class);
                        }
                        Trigger::Damaged { amount, source } => {
                            self.scopes[0].insert(amount.clone(), None);
                            if let Some(s) = source {
                                self.scopes[0].insert(s.clone(), None);
                            }
                        }
                        _ => {}
                    }
                    self.returns = None;
                    self.ind = 1;
                    self.body.clear();
                    self.block(body)?;
                    s.push_str(&std::mem::take(&mut self.body));
                    s.push_str("}\n");
                }
                ItemKind::Action { name, params, gives, body } => {
                    for line in self.notes_lines(&item.notes, 0) {
                        s.push_str(&line);
                    }
                    // A returned enum or struct is a type of this class, which isn't in scope before `Class::`.
                    let own_type = gives.as_ref().is_some_and(|g| matches!(Type::from_expr(g), Type::Enum(_) | Type::Struct(_)));
                    if own_type {
                        s.push_str(&format!("auto {class}::{}({}) -> {} {{\n", ident(name), self.param_list(params), self.ret_type(gives.as_ref())));
                    } else {
                        s.push_str(&format!("{} {class}::{}({}) {{\n", self.ret_type(gives.as_ref()), ident(name), self.param_list(params)));
                    }
                    self.scopes = vec![params.iter().map(|p| (p.name.clone(), None)).collect()];
                    self.returns = gives.as_ref().map(Type::from_expr);
                    self.ind = 1;
                    self.body.clear();
                    self.block(body)?;
                    if self.returns.is_some() {
                        self.line("return {};  // the default, if the action ends without `give back`");
                    }
                    s.push_str(&std::mem::take(&mut self.body));
                    s.push_str("}\n");
                }
            }
        }

        s.push_str("\n}  // namespace Propulsion::Script\n");
        Ok(s)
    }

    // ───────────────────────────── statements ─────────────────────────────

    fn line(&mut self, text: &str) {
        self.body.push_str(&"    ".repeat(self.ind));
        self.body.push_str(text);
        self.body.push('\n');
    }

    fn block(&mut self, body: &[Stmt]) -> Result<(), String> {
        self.scopes.push(HashMap::new());
        for s in body {
            self.stmt(s)?;
        }
        self.scopes.pop();
        Ok(())
    }

    /// A nested `{ ... }` block with its own scope and one more level of indentation.
    fn braced(&mut self, body: &[Stmt]) -> Result<(), String> {
        self.ind += 1;
        let r = self.block(body);
        self.ind -= 1;
        r
    }

    fn temp(&mut self, base: &str) -> String {
        self.counter += 1;
        format!("{base}{}", self.counter)
    }

    fn stmt(&mut self, s: &Stmt) -> Result<(), String> {
        for l in self.notes_lines(&s.notes, self.ind) {
            self.body.push_str(&l);
        }
        let trailing = s.notes.trailing.as_ref().map(|t| format!("  // {t}")).unwrap_or_default();
        match &s.kind {
            StmtKind::Make { target, value, limit } => {
                let v = self.limited(self.value(value), limit);
                self.assign(target, &v, &trailing);
            }
            StmtKind::Add { value, target, limit } => {
                if self.is_list(target) {
                    let list = self.term(target);
                    self.line(&format!("{list}.push_back({});{trailing}", self.value(value)));
                } else if limit.capped.is_none() && limit.floored.is_none() {
                    self.compound(target, "+=", &self.value(value), &trailing);
                } else {
                    let v = self.limited(format!("({} + {})", self.term(target), self.value(value)), limit);
                    self.assign(target, &v, &trailing);
                }
            }
            StmtKind::Subtract { value, target, limit } => {
                if limit.capped.is_none() && limit.floored.is_none() {
                    self.compound(target, "-=", &self.value(value), &trailing);
                } else {
                    let v = self.limited(format!("({} - {})", self.term(target), self.value(value)), limit);
                    self.assign(target, &v, &trailing);
                }
            }
            StmtKind::Multiply { target, value } => self.compound(target, "*=", &self.value(value), &trailing),
            StmtKind::Divide { target, value } => {
                let v = format!("Div({}, {})", self.term(target), self.value(value));
                self.assign(target, &v, &trailing);
            }
            StmtKind::Remove { value, list } => {
                let l = self.term(list);
                self.line(&format!("Erase({l}, {});{trailing}", self.value(value)));
            }
            StmtKind::RemoveAt { index, list } => {
                let l = self.term(list);
                self.line(&format!("EraseAt({l}, static_cast<int>({}));{trailing}", self.term(index)));
            }
            StmtKind::AddUnique { value, list } => {
                let l = self.term(list);
                self.line(&format!("AddUnique({l}, {});{trailing}", self.value(value)));
            }
            StmtKind::Clear(list) => self.line(&format!("{}.clear();{trailing}", self.term(list))),
            StmtKind::OnlyOnce { body, .. } => {
                let n = s.line;
                self.line(&format!("if (Latch_{n}_ == 0) {{{trailing}"));
                self.ind += 1;
                self.line(&format!("Latch_{n}_ = 1;"));
                self.ind -= 1;
                self.braced(body)?;
                self.line("}");
            }
            StmtKind::FirstTimes { count, body, .. } => {
                let n = s.line;
                self.line(&format!("if (Latch_{n}_ < static_cast<int>({})) {{{trailing}", self.term(count)));
                self.ind += 1;
                self.line(&format!("++Latch_{n}_;"));
                self.ind -= 1;
                self.braced(body)?;
                self.line("}");
            }
            StmtKind::Alternate { first, second, .. } => {
                let n = s.line;
                self.line(&format!("if (Latch_{n}_ == 0) {{{trailing}"));
                self.ind += 1;
                self.line(&format!("Latch_{n}_ = 1;"));
                self.ind -= 1;
                self.braced(first)?;
                self.line("} else {");
                self.ind += 1;
                self.line(&format!("Latch_{n}_ = 0;"));
                self.ind -= 1;
                self.braced(second)?;
                self.line("}");
            }
            StmtKind::GateChange { gate, change } => {
                let g = ident(gate);
                let text = match change {
                    GateChange::Open => format!("{g} = true;"),
                    GateChange::Close => format!("{g} = false;"),
                    GateChange::Toggle => format!("{g} = !{g};"),
                };
                self.line(&format!("{text}{trailing}"));
            }
            StmtKind::Through { gate, body } => {
                self.line(&format!("if ({}) {{{trailing}", ident(gate)));
                self.braced(body)?;
                self.line("}");
            }
            StmtKind::Choose { value, cases, otherwise } => {
                let chosen = self.temp("chosen_");
                self.line(&format!("{{{trailing}"));
                self.ind += 1;
                self.line(&format!("const auto {chosen} = {};", self.term(value)));
                for (i, case) in cases.iter().enumerate() {
                    let tests: Vec<String> = case.values.iter().map(|v| format!("{chosen} == {}", self.term(v))).collect();
                    let head = if i == 0 { "if" } else { "} else if" };
                    self.line(&format!("{head} ({}) {{", tests.join(" || ")));
                    self.braced(&case.body)?;
                }
                if let Some(body) = otherwise {
                    self.line("} else {");
                    self.braced(body)?;
                }
                self.line("}");
                self.ind -= 1;
                self.line("}");
            }
            StmtKind::Animate { var, from, to, seconds, body } => {
                let secs = match seconds {
                    Term::Duration(d) => float_lit(*d),
                    other => format!("static_cast<float>({})", self.term(other)),
                };
                let bound = |t: &Term| match t {
                    Term::Int(i) => float_lit(*i as f64),
                    other => self.term(other),
                };
                self.line(&format!(
                    "world->Animate(this, {}, {}, {secs}, [=, this](auto {}) mutable {{{trailing}",
                    bound(from),
                    bound(to),
                    ident(var)
                ));
                let saved = std::mem::replace(&mut self.returns, None);
                self.lambda_depth += 1;
                self.scopes.push(HashMap::from([(var.clone(), None)]));
                self.braced(body)?;
                self.scopes.pop();
                self.lambda_depth -= 1;
                self.returns = saved;
                self.line("});");
            }
            StmtKind::Damage { target, amount } => {
                self.line(&format!("world->Damage({}, static_cast<float>({}), self);{trailing}", self.term(target), self.value(amount)));
            }
            StmtKind::Attach { child, parent } => {
                self.line(&format!("world->Attach({}, {});{trailing}", self.term(child), self.term(parent)));
            }
            StmtKind::Detach(child) => self.line(&format!("world->Detach({});{trailing}", self.term(child))),
            StmtKind::Tell { target, action, args } => {
                let list: Vec<String> = args.iter().map(|a| format!("Arg{{{}, {}}}", c_str(&a.name), self.value(&a.value))).collect();
                self.line(&format!("world->Tell({}, {}, {{ {} }});{trailing}", self.term(target), c_str(action), list.join(", ")));
            }
            StmtKind::Do { action, on, args } => self.call_statement(action, on.as_deref(), args, &trailing)?,
            StmtKind::Send(e) => self.line(&format!("world->Send(this, {});{trailing}", c_str(e))),
            StmtKind::Remember { name, value } => {
                let class = match value {
                    Value::Term(Term::Name(n)) => self.class_of(n),
                    _ => None,
                };
                let v = self.value(value);
                self.line(&format!("auto {} = {v};{trailing}", ident(name)));
                if let Some(scope) = self.scopes.last_mut() {
                    scope.insert(name.clone(), class);
                }
            }
            StmtKind::Reset(t) => match self.latches.get(t) {
                Some(line) => self.line(&format!("Latch_{line}_ = 0;{trailing}")),
                None => self.line(&format!("{}.Reset(*world);{trailing}", ident(t))),
            },
            StmtKind::Spawn { file, at, name } => {
                let class = self.aliases.get(file).cloned().ok_or_else(|| format!("`{file}` isn't a file from the header"))?;
                self.line(&format!("Object* {} = world->SpawnFromScript<{class}>({});{trailing}", ident(name), self.value(at)));
                if let Some(scope) = self.scopes.last_mut() {
                    scope.insert(name.clone(), Some(class));
                }
            }
            StmtKind::Move { target, toward, by } => {
                let lvalue = self.lvalue(target);
                self.line(&format!("World::MoveToward({lvalue}, {}, {});{trailing}", self.value(toward), self.value(by)));
            }
            StmtKind::MoveDir { target, dir, by } => {
                let d = match dir {
                    Direction::Forward => "glm::vec3(0.0f, 1.0f, 0.0f)",
                    Direction::Back => "glm::vec3(0.0f, -1.0f, 0.0f)",
                    Direction::Left => "glm::vec3(-1.0f, 0.0f, 0.0f)",
                    Direction::Right => "glm::vec3(1.0f, 0.0f, 0.0f)",
                    Direction::Up => "glm::vec3(0.0f, 0.0f, 1.0f)",
                    Direction::Down => "glm::vec3(0.0f, 0.0f, -1.0f)",
                };
                self.line(&format!("world->MoveRelative({}, {d}, {});{trailing}", self.term(target), self.value(by)));
            }
            StmtKind::Print(v) => self.line(&format!("world->host().Print(ToText({}));{trailing}", self.value(v))),
            StmtKind::Destroy(t) => self.line(&format!("world->Destroy({});{trailing}", self.term(t))),
            StmtKind::GiveBack(v) => self.line(&format!("return {};{trailing}", self.value(v))),
            StmtKind::Finish => {
                let text = if self.returns.is_some() && self.lambda_depth == 0 { "return {};" } else { "return;" };
                self.line(&format!("{text}{trailing}"));
            }
            StmtKind::StopLoop => self.line(&format!("break;{trailing}")),
            StmtKind::Skip => self.line(&format!("continue;{trailing}")),
            StmtKind::If { branches, otherwise, .. } => {
                for (i, (cond, body)) in branches.iter().enumerate() {
                    let head = if i == 0 { "if" } else { "} else if" };
                    let tail = if i == 0 { trailing.clone() } else { String::new() };
                    self.line(&format!("{head} ({}) {{{tail}", self.condition(cond)));
                    self.braced(body)?;
                }
                if let Some(body) = otherwise {
                    self.line("} else {");
                    self.braced(body)?;
                }
                self.line("}");
            }
            StmtKind::Repeat { times, body } => {
                let i = self.temp("repeat_");
                self.line(&format!("for (int {i} = 0; {i} < static_cast<int>({}); ++{i}) {{{trailing}", self.term(times)));
                self.braced(body)?;
                self.line("}");
            }
            StmtKind::ForEach { var, list, body } => {
                let copy = self.temp("items_");
                let class = match list {
                    Term::Name(n) => self.entities.get(n).and_then(|e| e.class.clone()),
                    _ => None,
                };
                self.line(&format!("{{{trailing}"));
                self.ind += 1;
                self.line(&format!("auto {copy} = {};  // a copy, so changes to the list don't disturb the loop", self.term(list)));
                self.line(&format!("for (auto {} : {copy}) {{", ident(var)));
                self.scopes.push(HashMap::from([(var.clone(), class)]));
                self.braced(body)?;
                self.scopes.pop();
                self.line("}");
                self.ind -= 1;
                self.line("}");
            }
            StmtKind::ForRange { var, from, to, body } => {
                let v = ident(var);
                self.line(&format!("for (int {v} = static_cast<int>({}); {v} <= static_cast<int>({}); ++{v}) {{{trailing}", self.term(from), self.term(to)));
                self.scopes.push(HashMap::from([(var.clone(), None)]));
                self.braced(body)?;
                self.scopes.pop();
                self.line("}");
            }
            StmtKind::While { cond, body } => {
                let turns = self.temp("turns_");
                self.line(&format!("for (int {turns} = 0; {}; ++{turns}) {{{trailing}", self.condition(cond)));
                self.ind += 1;
                self.line(&format!("if ({turns} > 100000) {{ world->Warn(\"a `while` loop ran too long and was stopped\"); break; }}"));
                self.ind -= 1;
                self.braced(body)?;
                self.line("}");
            }
            StmtKind::After { seconds, body } => {
                let secs = match seconds {
                    Term::Duration(d) => float_lit(*d),
                    other => format!("static_cast<float>({})", self.term(other)),
                };
                self.line(&format!("world->After(this, {secs}, [=, this]() mutable {{{trailing}"));
                let saved = std::mem::replace(&mut self.returns, None);
                self.lambda_depth += 1;
                self.braced(body)?;
                self.lambda_depth -= 1;
                self.returns = saved;
                self.line("});");
            }
        }
        Ok(())
    }

    fn limited(&self, value: String, limit: &Limit) -> String {
        let mut v = value;
        if let Some(c) = &limit.capped {
            v = format!("Cap({v}, {})", self.term(c));
        }
        if let Some(f) = &limit.floored {
            v = format!("Floor({v}, {})", self.term(f));
        }
        v
    }

    fn is_list(&self, t: &Term) -> bool {
        matches!(t, Term::Name(n) if matches!(self.vars.get(n), Some(VarInfo { ty: Type::List(_), .. })))
    }

    /// `x = value;` for a name or a transform field.
    fn assign(&mut self, target: &Term, value: &str, trailing: &str) {
        if let Term::Path { segments, owner } = target {
            let who = match owner.as_deref() {
                None | Some("Self") => "self".to_string(),
                Some(o) => self.name(o),
            };
            match segments.first().map(String::as_str) {
                Some("Visibility") => return self.line(&format!("world->SetShown({who}, {value});{trailing}")),
                Some("Collision") => return self.line(&format!("world->SetCollision({who}, {value});{trailing}")),
                _ => {}
            }
        }
        let lv = self.lvalue(target);
        self.line(&format!("{lv} = {value};{trailing}"));
        self.after_write(target);
    }

    /// `x += value;` and friends.
    fn compound(&mut self, target: &Term, op: &str, value: &str, trailing: &str) {
        let lv = self.lvalue(target);
        self.line(&format!("{lv} {op} {value};{trailing}"));
        self.after_write(target);
    }

    /// Changing a rotation means refreshing the Transform's quaternion (TransformComponent.h).
    fn after_write(&mut self, target: &Term) {
        if let Term::Path { segments, owner } = target {
            if segments.get(1).map(String::as_str) == Some("Rot") {
                let base = self.transform_base(owner.as_deref());
                self.line(&format!("{base}updateQuaternion();"));
            }
        }
    }

    fn transform_base(&self, owner: Option<&str>) -> String {
        match owner {
            None | Some("Self") => "self->getTransform()->".to_string(),
            Some(o) => format!("world->TransformOf({}).", self.name(o)),
        }
    }

    fn lvalue(&self, t: &Term) -> String {
        self.term(t)
    }

    // ───────────────────────────── calls ─────────────────────────────

    /// The script class that a name's entity runs, if known.
    fn class_of(&self, name: &str) -> Option<String> {
        for scope in self.scopes.iter().rev() {
            if let Some(c) = scope.get(name) {
                return c.clone();
            }
        }
        self.entities.get(name).and_then(|e| e.class.clone())
    }

    fn actions_of(&self, class: &str) -> Option<&HashMap<String, ActionSig>> {
        let key = self.classes.iter().find(|(_, c)| c.as_str() == class).map(|(k, _)| k)?;
        Some(&self.project.files[key].sig.actions)
    }

    /// The arguments of a call, in the order the callee declares its parameters.
    fn ordered_args(&self, sigs: Option<&HashMap<String, ActionSig>>, action: &str, args: &[Arg]) -> Vec<String> {
        let params: Vec<String> = sigs
            .and_then(|s| s.get(action))
            .map(|s| s.params.iter().map(|(n, _)| n.clone()).collect())
            .unwrap_or_default();
        params
            .iter()
            .map(|p| args.iter().find(|a| a.name == *p).map(|a| self.value(&a.value)).unwrap_or_else(|| "{}".to_string()))
            .collect()
    }

    fn call_statement(&mut self, action: &str, on: Option<&str>, args: &[Arg], trailing: &str) -> Result<(), String> {
        match on {
            None | Some("Self") => {
                let own = &self.project.files[self.key].sig.actions;
                let a = self.ordered_args(Some(own), action, args).join(", ");
                self.line(&format!("{}({a});{trailing}", ident(action)));
            }
            Some(n) if self.systems.iter().any(|s| s == n) => {
                let list: Vec<String> = args.iter().map(|a| format!("Arg{{{}, {}}}", c_str(&a.name), self.value(&a.value))).collect();
                self.line(&format!("world->host().Call({}, {}, {{ {} }});{trailing}", c_str(n), c_str(action), list.join(", ")));
            }
            Some(n) if self.aliases.contains_key(n) => {
                let class = self.aliases[n].clone();
                let a = self.ordered_args(self.actions_of(&class), action, args).join(", ");
                self.line(&format!("world->Instance<{class}>()->{}({a});{trailing}", ident(action)));
            }
            Some(n) => {
                let class = self.class_of(n).ok_or_else(|| format!("can't tell which script `{n}` runs, so can't call `{action}` on it"))?;
                let a = self.ordered_args(self.actions_of(&class), action, args).join(", ");
                let who = self.temp("callee_");
                self.line(&format!("if (auto* {who} = world->As<{class}>({})) {{{trailing}", self.name(n)));
                self.ind += 1;
                self.line(&format!("{who}->{}({a});", ident(action)));
                self.ind -= 1;
                self.line(&format!("}} else {{ world->Warn(\"`{action}` was skipped because `{n}` is missing\"); }}"));
            }
        }
        Ok(())
    }

    // ───────────────────────────── expressions ─────────────────────────────

    /// How a name is written: a local, a member, or an accessor for an entity lookup.
    fn name(&self, n: &str) -> String {
        if n == "Self" {
            return "self".to_string();
        }
        if self.scopes.iter().any(|s| s.contains_key(n)) {
            return ident(n);
        }
        if let Some(en) = self.enum_values.get(n) {
            return format!("{}::{}", ident(en), ident(n));
        }
        if self.entities.contains_key(n) {
            return format!("{}()", ident(n));
        }
        ident(n)
    }

    fn term(&self, t: &Term) -> String {
        match t {
            Term::Int(i) => i.to_string(),
            Term::Decimal(d) => float_lit(*d),
            Term::Text(s) => string_lit(s),
            Term::Bool(b) => b.to_string(),
            Term::Duration(d) => format!("{d:?}"),
            Term::Name(n) => self.name(n),
            Term::Path { segments, owner } if matches!(segments.first().map(String::as_str), Some("Visibility" | "Collision")) => {
                let who = match owner.as_deref() {
                    None | Some("Self") => "self".to_string(),
                    Some(o) => self.name(o),
                };
                match segments[0].as_str() {
                    "Visibility" => format!("world->IsShown({who})"),
                    _ => format!("world->IsCollidable({who})"),
                }
            }
            Term::Path { segments, .. } if !matches!(segments[0].as_str(), "Transform" | "Visibility" | "Collision") => {
                // A part of a vector (`Velocity.X` is `Velocity.x`) or a field of a struct (`Held.Cost`). No struct
                // has a field named like a part, so the name says which.
                let mut out = self.name(&segments[0]);
                for part in &segments[1..] {
                    match part.as_str() {
                        "X" | "Y" | "Z" | "R" | "G" | "B" | "A" | "Pitch" | "Yaw" | "Roll" => out.push_str(&format!(".{}", part_member(part))),
                        field => out.push_str(&format!(".{}", ident(field))),
                    }
                }
                out
            }
            Term::Path { segments, owner } => {
                let base = self.transform_base(owner.as_deref());
                let field = match segments.get(1).map(String::as_str) {
                    Some("Loc") => "position",
                    Some("Rot") => "rotation",
                    _ => "scale",
                };
                let axis = segments.get(2).map(|a| format!(".{}", part_member(a))).unwrap_or_default();
                format!("{base}{field}{axis}")
            }
        }
    }

    fn value(&self, v: &Value) -> String {
        match v {
            Value::Term(t) => self.term(t),
            Value::PerSecond(t) => format!("({} * world->dt)", self.term(t)),
            Value::Distance { from, to } => format!("world->Distance({}, {})", self.term(from), self.term(to)),
            Value::CountOf(t) => format!("static_cast<int>({}.size())", self.term(t)),
            Value::ItemOf { index, list } => format!("Item({}, {})", self.term(list), self.term(index)),
            Value::JoinedWith { left, right } => format!("(ToText({}) + ToText({}))", self.term(left), self.term(right)),
            Value::TextOf(t) => format!("ToText({})", self.term(t)),
            Value::DecimalOf(t) => format!("static_cast<float>({})", self.term(t)),
            Value::IntegerOf(t) => format!("static_cast<int>({})", self.term(t)),
            Value::AbsoluteValueOf(t) => format!("std::abs({})", self.term(t)),
            Value::ResultOf { action, args } => {
                let own = &self.project.files[self.key].sig.actions;
                format!("{}({})", ident(action), self.ordered_args(Some(own), action, args).join(", "))
            }
            Value::Vector { x, y, z } => format!("glm::vec3({}, {}, {})", self.term(x), self.term(y), self.term(z)),
            Value::TimeSinceStart => "static_cast<float>(world->Time())".to_string(),
            Value::Lerp { t, from, to } => format!("Lerp({}, {}, {})", self.term(from), self.term(to), self.term(t)),
            Value::Axis { system, input } => format!("world->host().Axis(self, {}, {})", c_str(system), c_str(input)),
            Value::Arith { left, op, right } => {
                let (l, r) = (self.term(left), self.term(right));
                match op {
                    ArithOp::Plus => format!("({l} + {r})"),
                    ArithOp::Minus => format!("({l} - {r})"),
                    ArithOp::Times => format!("({l} * {r})"),
                    ArithOp::DividedBy => format!("Div({l}, {r})"),
                    ArithOp::Remainder => format!("Mod({l}, {r})"),
                }
            }
            Value::Condition(c) => format!("({})", self.condition(c)),
            Value::Phrase { node, args } => {
                let Some(def) = crate::phrases::find(node) else { return "{}".to_string() };
                let mut out = def.cpp.to_string();
                for (i, a) in args.iter().enumerate().rev() {
                    out = out.replace(&format!("{{{i}}}"), &self.term(a));
                }
                out
            }
            Value::Pick { yes, cond, no } => format!("(({}) ? {} : {})", self.condition(cond), self.term(yes), self.term(no)),
            Value::CastTo { value, file } => {
                let class = self.aliases.get(file).cloned().unwrap_or_else(|| "ScriptBehavior".to_string());
                format!("world->CastTo<{class}>({})", self.term(value))
            }
            Value::NewStruct { ty, args } => {
                let sets: Vec<String> = args.iter().map(|a| format!("v.{} = {};", ident(&a.name), self.value(&a.value))).collect();
                format!("([&] {{ {} v{{}}; {} return v; }}())", ident(ty), sets.join(" "))
            }
            Value::RowOf { key, table } => format!("Row_{}({})", ident(table), self.term(key)),
            Value::Format { parts } => {
                let pieces: Vec<String> = parts
                    .iter()
                    .map(|p| match p {
                        FormatPart::Text(t) => string_lit(t),
                        FormatPart::Value(t) => format!("ToText({})", self.term(t)),
                    })
                    .collect();
                match pieces.len() {
                    0 => "std::string()".to_string(),
                    1 => pieces[0].clone(),
                    _ => format!("({})", pieces.join(" + ")),
                }
            }
        }
    }

    fn condition(&self, c: &Condition) -> String {
        let joiner = if c.joiner == Some(Joiner::Or) { " || " } else { " && " };
        let parts: Vec<String> = std::iter::once(&c.first).chain(c.rest.iter()).map(|x| self.comparison(x)).collect();
        parts.join(joiner)
    }

    fn comparison(&self, c: &Comparison) -> String {
        match c {
            Comparison::Compare { left, op, right } => {
                let word = match op {
                    CmpOp::Eq => "==",
                    CmpOp::NotEq => "!=",
                    CmpOp::Above => ">",
                    CmpOp::Below => "<",
                    CmpOp::AtLeast => ">=",
                    CmpOp::AtMost => "<=",
                };
                // A timer is compared with a duration by how long it has been running.
                let l = match left {
                    Value::Term(Term::Name(n)) if matches!(self.vars.get(n), Some(VarInfo { ty: Type::Timer, .. })) => {
                        format!("{}.Elapsed(*world)", ident(n))
                    }
                    other => self.value(other),
                };
                format!("({l} {word} {})", self.value(right))
            }
            Comparison::Pressing { system, input, kind } => {
                let (s, i) = (c_str(system), c_str(input));
                match kind {
                    PressKind::Held => format!("world->host().Pressing(self, {s}, {i})"),
                    PressKind::NotHeld => format!("!world->host().Pressing(self, {s}, {i})"),
                    PressKind::Started => format!("world->host().Started(self, {s}, {i})"),
                    PressKind::Stopped => format!("world->host().Stopped(self, {s}, {i})"),
                }
            }
            Comparison::Presence { value, missing } => {
                let v = self.value(value);
                if *missing {
                    format!("!Present({v})")
                } else {
                    format!("Present({v})")
                }
            }
            Comparison::Contains { list, item, negated } => {
                let found = format!("Contains({}, {})", self.value(list), self.value(item));
                if *negated {
                    format!("!{found}")
                } else {
                    found
                }
            }
        }
    }
}

/// The statements that keep state between runs (`only once`, `first N times`, `alternate`): the line each is on,
/// and a few words for the comment next to its counter. `names` collects the ones that have a name.
fn latch_sites(body: &[Stmt], names: &mut HashMap<String, usize>, sites: &mut Vec<(usize, String)>) {
    for s in body {
        let mut site = |name: &Option<String>, what: &str| {
            if let Some(n) = name {
                names.insert(n.clone(), s.line);
            }
            let label = match name {
                Some(n) => format!("{what} as {n}"),
                None => what.to_string(),
            };
            sites.push((s.line, label));
        };
        match &s.kind {
            StmtKind::OnlyOnce { name, body } => {
                site(name, "only once");
                latch_sites(body, names, sites);
            }
            StmtKind::FirstTimes { name, body, .. } => {
                site(name, "first N times");
                latch_sites(body, names, sites);
            }
            StmtKind::Alternate { name, first, second } => {
                site(name, "alternate");
                latch_sites(first, names, sites);
                latch_sites(second, names, sites);
            }
            StmtKind::If { branches, otherwise, .. } => {
                for (_, b) in branches {
                    latch_sites(b, names, sites);
                }
                if let Some(b) = otherwise {
                    latch_sites(b, names, sites);
                }
            }
            StmtKind::Choose { cases, otherwise, .. } => {
                for c in cases {
                    latch_sites(&c.body, names, sites);
                }
                if let Some(b) = otherwise {
                    latch_sites(b, names, sites);
                }
            }
            StmtKind::Repeat { body, .. }
            | StmtKind::ForEach { body, .. }
            | StmtKind::ForRange { body, .. }
            | StmtKind::While { body, .. }
            | StmtKind::After { body, .. }
            | StmtKind::Through { body, .. }
            | StmtKind::Animate { body, .. } => latch_sites(body, names, sites),
            _ => {}
        }
    }
}

/// The member of a glm vector that a part name picks out: `X` and `Pitch` are `x`, `Y` and `Roll` are `y`, `Z` and
/// `Yaw` are `z`, and `R` is `x` of a color too.
fn part_member(part: &str) -> &'static str {
    match part {
        "X" | "Pitch" | "R" => "x",
        "Y" | "Roll" | "G" => "y",
        "Z" | "Yaw" | "B" => "z",
        _ => "w",
    }
}
